#!/usr/bin/env bash
# Write <repo>/.github/workflows/platform.yml calling the platform reusable workflows at one pinned SHA.
# Usage: render.sh <repo-dir> --ref <40-hex sha> [--platform-repo owner/name]
set -euo pipefail
repo=${1:?usage: render.sh <repo-dir> --ref <sha>}
shift
ref="" platform=AustinRP2008/platform-skills
while [[ $# -gt 0 ]]; do
  case $1 in
    --ref) ref=$2;; --platform-repo) platform=$2;;
    *) echo "unknown arg $1" >&2; exit 64;;
  esac
  shift 2
done
[[ $ref =~ ^[0-9a-f]{40}$ ]] || { echo "--ref must be a full 40-char commit sha (got '$ref')" >&2; exit 64; }
here=$(cd "$(dirname "$0")" && pwd)
out="$repo/.github/workflows/platform.yml"
[[ -e $out ]] && { echo "refusing: $out exists" >&2; exit 65; }
targets=$("$here/detect.sh" "$repo")
[[ -n $targets ]] || { echo "no CI targets found in $repo (see references/ci-contract.md)" >&2; exit 66; }
mkdir -p "$(dirname "$out")"

declare -A wf=([tofu]=reusable-tofu-module.yml [k8s]=reusable-k8s-app.yml [prometheus]=reusable-prometheus-rules.yml [image]=reusable-golden-image.yml)
{
  echo "# Generated by the onboarding-repo-ci skill. Bump the sha to take platform fixes."
  echo "name: platform"
  echo "on:"
  echo "  pull_request:"
  echo "  push:"
  echo "    branches: [main]"
  echo "permissions:"
  echo "  contents: read"
  echo "jobs:"
  for kind in tofu k8s prometheus image; do
    paths=$(awk -F'\t' -v k="$kind" '$1==k {print $2}' <<< "$targets")
    [[ -n $paths ]] || continue
    echo "  $kind:"
    echo "    strategy:"
    echo "      fail-fast: false"
    echo "      matrix:"
    echo "        path:"
    while IFS= read -r p; do echo "          - \"$p\""; done <<< "$paths"
    echo "    uses: $platform/.github/workflows/${wf[$kind]}@$ref"
    echo "    with:"
    echo "      path: \${{ matrix.path }}"
    echo "      platform-ref: $ref"
  done
} > "$out"
echo "$out"
